package LeTranTrungHieu_2793.Lec02_Variable;

public class OperatorExample {

    public static void main(String[] args) {
        int x = 1;
        System.out.println("x = " + x++);
        System.out.println("x = " + x);
        
        int y = 2;
        System.out.println("y = " + ++y);
        System.out.println("y = " + y);
    }
}
